const EDUCATION_KANJI_SET = new Set(
  (GRADE1 + GRADE2 + GRADE3 + GRADE4 + GRADE5 + GRADE6).split("").filter((c) => c.trim() !== "")
);

// 《読み》つきで書かれた「漢字《かんじ》」の並びを、判定の対象から外すための正規表現。
const RUBY_ANNOTATED_RE = /[一-鿿㐀-䶿々〆〇〻]+《[^《》]*》/g;
const KANJI_CHAR_RE = /[一-鿿㐀-䶿]/g;

// 一覧にない漢字が、ふりがな（《》）なしでそのまま含まれていないかを調べる。
// 警告用の関数なので、一覧の取りこぼしで誤って壊れることはない
// （見つかっても表示は止めず、保護者画面に小さく注意を出すだけに使うこと）。
export function hasHardKanji(text) {
  const withoutRuby = String(text ?? "").replace(RUBY_ANNOTATED_RE, "");
  const chars = withoutRuby.match(KANJI_CHAR_RE);
  if (!chars) return false;
  return chars.some((c) => !EDUCATION_KANJI_SET.has(c));
}
